/** A believable class: computes fine, struggles to formulate. Deterministic. */
export function demoClass(): Summary[] {
  const rng = mulberry32(2026);
  return NAMES.map((name) => {
    const n = 6 + Math.floor(rng() * 7);
    const rate: Record<Stage, number> = {
      formulate: 0.25 + rng() * 0.45,
      employ: 0.6 + rng() * 0.35,
      interpret: 0.4 + rng() * 0.4,
    };
    const stages = {} as Summary["stages"];
    const errors = Object.fromEntries(ERROR_TYPES.map((e) => [e, 0])) as Summary["errors"];
    for (const s of STAGES) {
      let ok = 0;
      for (let i = 0; i < n; i++) if (rng() < rate[s]) ok++;
      stages[s] = { ok, total: n };
      const bad = n - ok;
      for (let i = 0; i < bad; i++) {
        const r = rng();
        const e: ErrorType =
          s === "formulate"
            ? r < 0.55 ? "ignored_condition" : r < 0.85 ? "wrong_data" : "partial_solution"
            : s === "employ"
              ? r < 0.35 ? "unit_error" : r < 0.6 ? "partial_solution" : r < 0.8 ? "wrong_operation" : "calc_slip"
              : r < 0.8 ? "no_interpretation" : "ignored_condition";
        errors[e]++;
      }
    }
    return { name, stages, errors };
  });
}

